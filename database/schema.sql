CREATE DATABASE IF NOT EXISTS `05_ltgics_db` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `05_ltgics_db`;

CREATE TABLE IF NOT EXISTS `users` (
  UserID INT AUTO_INCREMENT PRIMARY KEY,
  FullName VARCHAR(100) NOT NULL,
  Email VARCHAR(160) NOT NULL UNIQUE,
  PasswordHash VARCHAR(255) NOT NULL,
  Role VARCHAR(30) NOT NULL DEFAULT 'user',
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UpdatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `guide_profiles` (
  id INT AUTO_INCREMENT PRIMARY KEY,
  `Bio` TEXT NULL,
  `LicenseNumber` VARCHAR(255) NOT NULL,
  `Availability` VARCHAR(255) NOT NULL,
  `UserID` INT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `fk_guide_profiles_userid` FOREIGN KEY (`UserID`) REFERENCES `users` (`UserID`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `languages` (
  id INT AUTO_INCREMENT PRIMARY KEY,
  `LanguageName` VARCHAR(255) NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `guide_languages` (
  id INT AUTO_INCREMENT PRIMARY KEY,
  `GuideID` INT NOT NULL,
  `LanguageID` INT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `fk_guide_languages_guideid` FOREIGN KEY (`GuideID`) REFERENCES `guide_profiles` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_guide_languages_languageid` FOREIGN KEY (`LanguageID`) REFERENCES `languages` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `bookings` (
  id INT AUTO_INCREMENT PRIMARY KEY,
  `TourDate` DATETIME NOT NULL,
  `Status` VARCHAR(255) NOT NULL,
  `UserID` INT NOT NULL,
  `GuideID` INT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `fk_bookings_userid` FOREIGN KEY (`UserID`) REFERENCES `users` (`UserID`) ON DELETE RESTRICT,
  CONSTRAINT `fk_bookings_guideid` FOREIGN KEY (`GuideID`) REFERENCES `guide_profiles` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
